// Renders docs/api/*-v1.md and docs/integrations/*-v1.md to HTML at build time into lib/docs.generated.ts (gitignored).
// The /docs pages import that module, so nothing reads the markdown files at runtime.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { Marked } from 'marked'

const root = fileURLToPath(new URL('../../../', import.meta.url))
const dir = `${root}docs/api/`
const integrationsDir = `${root}docs/integrations/`
const out = fileURLToPath(new URL('../lib/docs.generated.ts', import.meta.url))

const INTEGRATIONS = ['html', 'wordpress', 'ghost', 'discourse']
const ORDER = ['README', 'examples', 'hashing', 'json-mode', 'format-quality', 'cache-ttl', 'usage', 'gravatar-differences', 'errors']
const slugOf = (file) => file.replace(/-v1\.md$/, '')
const urlOf = (slug) => (slug === 'README' ? '/docs' : `/docs/${slug}`)

export const slugify = (text) =>
  text.toLowerCase().replace(/<[^>]*>/g, '').replace(/&[a-z]+;/g, '').replace(/[^a-z0-9\s_-]/g, '').trim().replace(/\s+/g, '-')

export function render(slug, markdown) {
  const headings = []
  const seen = new Map()
  const marked = new Marked({
    renderer: {
      heading({ tokens, depth }) {
        const html = this.parser.parseInline(tokens)
        const text = tokens.map((t) => t.raw ?? t.text ?? '').join('').replace(/`/g, '')
        const base = slugify(text)
        const n = seen.get(base) ?? 0
        seen.set(base, n + 1)
        const id = n === 0 ? base : `${base}-${n}`
        if (depth === 2) headings.push({ id, text })
        return `<h${depth} id="${id}"><a class="anchor" href="#${id}" aria-label="Link to ${text.replace(/"/g, '')}">#</a>${html}</h${depth}>\n`
      },
      link({ href, title, tokens }) {
        const m = /^(?:\.\.\/(api|integrations)\/)?([\w-]+)-v1\.md(#.*)?$/.exec(href)
        const to = m ? `${urlOf(m[1] === 'integrations' ? `integrations-${m[2]}` : m[2])}${m[3] ?? ''}` : href
        const t = title ? ` title="${title}"` : ''
        return `<a href="${to}"${t}>${this.parser.parseInline(tokens)}</a>`
      },
      table(token) {
        const head = token.header.map((c, i) => `<th${token.align[i] ? ` align="${token.align[i]}"` : ''}>${this.parser.parseInline(c.tokens)}</th>`).join('')
        const rows = token.rows
          .map((r) => `<tr>${r.map((c) => `<td>${this.parser.parseInline(c.tokens)}</td>`).join('')}</tr>`)
          .join('\n')
        return `<div class="docs-table" role="region" aria-label="Table" tabindex="0"><table><thead><tr>${head}</tr></thead><tbody>${rows}</tbody></table></div>\n`
      },
    },
  })
  let html = marked.parse(markdown, { async: false })
  // Error codes are linked from API responses as /docs/errors#<code>.
  if (slug === 'errors') html = html.replace(/<td><code>(\w+)<\/code><\/td>/g, (m, code) => `<td id="${code}"><code>${code}</code></td>`)
  return { html, headings }
}

export function build() {
  const files = readdirSync(dir).filter((f) => f.endsWith('-v1.md'))
  const pages = files
    .map((f) => {
      const key = slugOf(f)
      const md = readFileSync(`${dir}${f}`, 'utf8')
      const title = /^# (.+)$/m.exec(md)?.[1] ?? key
      const { html, headings } = render(key, md)
      return { group: 'api', slug: key === 'README' ? '' : key, title: key === 'README' ? 'API reference' : title.replace(/ \(v1\)$/, ''), html, headings }
    })
    .sort((a, b) => ORDER.indexOf(a.slug || 'README') - ORDER.indexOf(b.slug || 'README'))
  const guides = INTEGRATIONS.map((name) => {
    const md = readFileSync(`${integrationsDir}${name}-v1.md`, 'utf8')
    const { html, headings } = render(`integrations-${name}`, md)
    const title = /^# (.+)$/m.exec(md)?.[1] ?? name
    return { slug: `integrations-${name}`, title: title.replace(/ \(v1\)$/, ''), html, headings, group: 'integrations' }
  })
  const extra = readdirSync(integrationsDir).filter((f) => f.endsWith('-v1.md') && !INTEGRATIONS.includes(slugOf(f)))
  if (extra.length) throw new Error(`docs/integrations page missing from INTEGRATIONS in build-docs.mjs: ${extra.join(', ')}`)
  const unknown = pages.filter((p) => !ORDER.includes(p.slug || 'README')).map((p) => p.slug)
  if (unknown.length) throw new Error(`docs/api page missing from ORDER in build-docs.mjs: ${unknown.join(', ')}`)
  pages.push(...guides)
  writeFileSync(
    out,
    `// Generated by scripts/build-docs.mjs from docs/api/*-v1.md. Do not edit.\nexport interface DocPage { group: 'api' | 'integrations'; slug: string; title: string; html: string; headings: { id: string; text: string }[] }\nexport const DOC_PAGES: DocPage[] = ${JSON.stringify(pages, null, 2)}\n`,
  )
  return pages
}

if (process.argv[1] === fileURLToPath(import.meta.url)) build()
